class Superheat134aCalculation:
    def __init__(self, inputs: Dict[str, str] | None):
        self.superheated_tables = superheat_134a_data 

        if inputs:
            self.pressure = float(inputs.get("pressure", 0))
            self.temperature = float(inputs.get("temperature", 0))
        else:
            self.pressure = 0.0
            self.temperature = 0.0

    def get_properties(self, pressure: float, temp: float):
        """Interpolate within a pressure table by T, then (if needed) between pressure tables."""
        pressures = sorted(self.superheated_tables.keys())

        if pressure in self.superheated_tables:
            return self._interp_within_table(self.superheated_tables[pressure], temp)

        p_low, p_high = None, None
        for p in pressures:
            if p < pressure:
                p_low = p
            elif p > pressure and p_high is None:
                p_high = p
                break

        if p_low is None or p_high is None:
            raise ValueError(f"Pressure {pressure} out of range.")

        props_low  = self._interp_within_table(self.superheated_tables[p_low],  temp)
        props_high = self._interp_within_table(self.superheated_tables[p_high], temp)

        ratio = (pressure - p_low) / (p_high - p_low)
        return [
            props_low[i] + (props_high[i] - props_low[i]) * ratio
            for i in range(4)
        ]

    def _interp_within_table(self, table: Dict[float, List[float]] | Dict, temp: float):
        """Linear interpolation in temperature for a single pressure table."""
        temps = sorted(t for t in table.keys() if isinstance(t, (int, float)))

        if temp in table:
            return table[temp]

        lower, higher = None, None
        for t in temps:
            if t < temp:
                lower = t
            elif t > temp and higher is None:
                higher = t
                break

        if lower is None or higher is None:
            raise ValueError(f"Temperature {temp}°C out of range.")

        v1, u1, h1, s1 = table[lower]
        v2, u2, h2, s2 = table[higher]
        ratio = (temp - lower) / (higher - lower)

        return [
            v1 + (v2 - v1) * ratio,
            u1 + (u2 - u1) * ratio,
            h1 + (h2 - h1) * ratio,
            s1 + (s2 - s1) * ratio,
        ]

    def calculate(self) -> Dict[str, float]:
        try:
            v, u, h, s = self.get_properties(self.pressure, self.temperature)
            return {
                "Pressure<br>(<em>P</em>, bar)": round(self.pressure, 3),
                "Temperature<br>(<em>T</em>, °C)": round(self.temperature, 2),
                "Specific Volume<br>(<em>v</em>, m³/kg)": f"{v:.6f}",
                "Internal Energy<br>(<em>u</em>, kJ/kg)": round(u, 2),
                "Enthalpy<br>(<em>h</em>, kJ/kg)": round(h, 2),
                "Entropy<br>(<em>s</em>, kJ/kg·K)": f"{s:.5}",
            }
        except ValueError as e:
            raise ValueError(str(e))